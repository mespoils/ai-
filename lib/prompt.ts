export function buildPrompt(input: GenerateInput): string {
  const guide = TYPE_GUIDES[input.copy_type] ?? "";

  let prompt = `你是一位资深文案策划师。用户的输入不是关键词，而是对需求的具体描述。

请按以下步骤工作：

**第一步：分析用户需求**
仔细阅读用户的描述，从中提取以下信息：
- 用户想表达什么核心信息？
- 目标受众是谁？
- 期望达到什么效果？
- 有没有隐藏的情绪或诉求？
- 结合场景和风格，文案应该用什么语调和角度？

**第二步：根据分析结果生成文案**
基于以上分析，结合写作要求，生成最适合的文案。

---

【文案类型】${input.copy_type}
【风格要求】${input.style}
【使用场景】${input.scenario}
【用户需求】${input.topic}`;

  if (input.reference_image) {
    prompt += `\n【参考图片】用户已上传一张参考图片，请分析图片中的视觉风格、排版、色调、元素等内容，将其作为文案风格和视觉调性的参考。`;
  }

  if (input.extra_requirements) {
    prompt += `\n【补充要求】${input.extra_requirements}`;
  }

  prompt += `\n${guide}\n直接输出文案内容，不要输出分析过程。`;

  return prompt;
}
